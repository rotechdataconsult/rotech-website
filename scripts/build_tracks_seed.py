"""Build rotech-tracks-seed.sql from curriculum/tracks.json.

Each track becomes a domain, each week a module, and each week gets four
lessons: one per live session plus the week's deliverable. IDs are
deterministic (uuid5), so the seed can be re-run after editing tracks.json
and will update rows in place instead of duplicating them.

Usage:  python scripts/build_tracks_seed.py
Then paste rotech-tracks-seed.sql into Supabase → SQL Editor and run it.
"""
import json
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NS = uuid.UUID("6a2c9100-0000-4000-8000-526f74656368")  # fixed namespace for Rotech track IDs

# Per-track presentation details the curriculum page doesn't carry.
# skills: chips on the landing page card. tools: the badge on each week's module card, one per week.
META = {
    "RT-AIA": dict(icon="🤖", level="Beginner", bg="#FCE7F3", fg="#BE185D",
                   skills=["n8n", "Prompting", "APIs & Webhooks", "AI Agents"],
                   tools=["AI", "AI", "n8n", "APIs", "n8n", "n8n", "AI", "AI", "n8n", "Capstone"]),
    "RT-PY":  dict(icon="🐍", level="Beginner", bg="#EDE9FE", fg="#7C3AED",
                   skills=["Python", "Git & GitHub", "pytest", "FastAPI"],
                   tools=["Python"] * 9 + ["SQL", "Python", "Capstone"]),
    "RT-UX":  dict(icon="🎨", level="Beginner", bg="#FFEDD5", fg="#C2410C",
                   skills=["User Research", "Figma", "Prototyping", "Usability Testing"],
                   tools=["UX Research"] * 4 + ["Figma"] * 4 + ["UX Research", "Figma", "Portfolio", "Capstone"]),
    "RT-HDA": dict(icon="🏥", level="Intermediate", bg="#DCFCE7", fg="#15803D",
                   skills=["DHIS2", "Data Quality", "Power BI", "Epidemiology"],
                   tools=["Health Data", "Excel", "DHIS2", "DHIS2", "SQL", "JMP", "Power BI", "Power BI", "Health Data", "Capstone"]),
    "RT-DAA": dict(icon="📒", level="Intermediate", bg="#FEF9C3", fg="#A16207",
                   skills=["Power Query", "Reconciliations", "Power BI", "Audit Analytics"],
                   tools=["Excel", "Power Query", "Excel", "Power BI", "Power BI", "SQL", "Excel", "Capstone"]),
    "RT-DAE": dict(icon="⚙️", level="Intermediate", bg="#DBEAFE", fg="#1D4ED8",
                   skills=["Python", "SPC", "Design of Experiments", "Reliability"],
                   tools=["Excel", "Python", "JMP", "JMP", "JMP", "Python", "JMP", "Python", "Power BI", "Capstone"]),
    "RT-CYB": dict(icon="🛡️", level="Beginner", bg="#E0F2FE", fg="#0369A1",
                   skills=["Linux", "Networking", "SIEM", "Incident Response"],
                   tools=["Security", "Networking", "Linux", "Python", "Security", "Security", "Networking", "Security",
                          "Security", "Security", "SIEM", "Security", "Cloud", "GRC", "AI", "Capstone"]),
}

SESSION_PLAN = """| Part | Time |
|------|------|
| Concept walkthrough | 25 min |
| Guided lab | 60 min |
| Practice on your own | 25 min |
| Explain-it-back check | 10 min |"""


def uid(*parts):
    return str(uuid.uuid5(NS, "/".join(str(p) for p in parts)))


def q(text):
    return "'" + str(text).replace("'", "''") + "'"


def session_lesson(track, n, week_title, topic, k, tool, ship):
    return f"""## {topic}

**{track['name']} · Week {n}: {week_title} · Session {k} of 3**

### How the session runs

{SESSION_PLAN}

### Main tool

{tool}

### Before you leave

- Write three sentences in your learning log: what you did, what broke, and how you fixed it.
- If you used AI, add an entry to your AI-use log: what you asked, what you kept, what you corrected.
- This session builds towards this week's deliverable: **{ship}**."""


def ship_lesson(track, n, week_title, ship, is_last):
    body = f"""## Week {n} deliverable: {ship}

**{track['name']} · Week {n}: {week_title}**

Every Rotech week ends with something you have built. This one goes into your public portfolio.

### Submission checklist

- [ ] The deliverable is saved to your portfolio (GitHub, Behance, Notion or a Power BI link)
- [ ] A short README: the problem, your approach, and the result
- [ ] An AI-use log entry for this week
- [ ] You can explain it to an instructor in 5 minutes"""
    if is_last:
        body += f"""

### Capstone brief

{track['capstone']}

Your capstone is defended live in front of a panel. Grading: 40% weekly labs, 20% mid-course project, 30% capstone, 10% live defence and AI-use log."""
    return body


def build():
    tracks = json.loads((ROOT / "curriculum" / "tracks.json").read_text(encoding="utf-8"))
    out = [
        "-- ═══════════════════════════════════════════════════════════════════════════",
        "-- ROTECH LMS — 7 ACADEMY TRACKS (generated by scripts/build_tracks_seed.py)",
        "-- Do not edit by hand: edit curriculum/tracks.json and re-run the script.",
        "-- Run in: Supabase Dashboard → SQL Editor → New Query. Safe to re-run.",
        "-- ═══════════════════════════════════════════════════════════════════════════",
        "",
        "BEGIN;",
        "",
    ]
    for t_i, t in enumerate(tracks):
        m = META[t["code"]]
        weeks = [w for _, ws in t["phases"] for w in ws]
        assert len(weeks) == t["weeks"] == len(m["tools"]), t["code"]
        dom = uid(t["code"])
        desc = f"{t['pitch']} {t['weeks']} weeks, 3 live sessions a week. For: {t['who']}"

        out += [f"-- ── {t['name']} ({t['code']}) " + "─" * 40,
                "INSERT INTO domains (id, title, icon, description, is_active) VALUES",
                f"  ({q(dom)}, {q(t['name'])}, {q(m['icon'])}, {q(desc)}, true)",
                "ON CONFLICT (id) DO UPDATE SET title = EXCLUDED.title, icon = EXCLUDED.icon,",
                "  description = EXCLUDED.description, is_active = EXCLUDED.is_active;", ""]

        mod_rows, lesson_rows = [], []
        for n, (title, topics, ship) in enumerate(weeks, 1):
            mod = uid(t["code"], "week", n)
            tool = m["tools"][n - 1]
            mdesc = f"Covers: {'; '.join(topics)}. Deliverable: {ship}."
            mod_rows.append(f"  ({q(mod)}, {q(dom)}, {q(title)}, {q(mdesc)}, {q(tool)}, {n})")
            for k, topic in enumerate(topics, 1):
                lesson_rows.append(
                    f"  ({q(uid(t['code'], 'week', n, 'session', k))}, {q(mod)}, {q(topic)}, "
                    f"{q(session_lesson(t, n, title, topic, k, tool, ship))}, "
                    f"{q('reading' if k == 1 else 'exercise')}, {k})")
            lesson_rows.append(
                f"  ({q(uid(t['code'], 'week', n, 'ship'))}, {q(mod)}, {q('Deliverable: ' + ship)}, "
                f"{q(ship_lesson(t, n, title, ship, n == len(weeks)))}, 'project', 4)")

        out += ["INSERT INTO modules (id, domain_id, title, description, tool, order_index) VALUES",
                ",\n".join(mod_rows),
                "ON CONFLICT (id) DO UPDATE SET title = EXCLUDED.title, description = EXCLUDED.description,",
                "  tool = EXCLUDED.tool, order_index = EXCLUDED.order_index;", "",
                "INSERT INTO lessons (id, module_id, title, content, lesson_type, order_index) VALUES",
                ",\n".join(lesson_rows),
                "ON CONFLICT (id) DO UPDATE SET title = EXCLUDED.title, content = EXCLUDED.content,",
                "  lesson_type = EXCLUDED.lesson_type, order_index = EXCLUDED.order_index;", ""]

    # Landing page "Learning Programs" cards
    prog_rows = []
    for t_i, t in enumerate(tracks):
        m = META[t["code"]]
        skills = "{" + ",".join('"' + s.replace('"', '') + '"' for s in m["skills"]) + "}"
        prog_rows.append(
            f"  ({q(uid(t['code'], 'program'))}, {q(t['name'])}, {q(t['pitch'])}, {q(m['icon'])}, {q(m['bg'])}, "
            f"{q(m['fg'])}, {q(m['level'])}, {q(str(t['weeks']) + ' weeks')}, {q(str(t['weeks'] * 4) + ' lessons')}, "
            f"{q(skills)}, '/auth/register', true, {t_i})")
    out += ["-- ── Landing page programme cards " + "─" * 40,
            "INSERT INTO lp_programs (id, title, description, icon, icon_bg, icon_color, level, duration, lessons, skills, cta_href, is_active, sort_order) VALUES",
            ",\n".join(prog_rows),
            "ON CONFLICT (id) DO UPDATE SET title = EXCLUDED.title, description = EXCLUDED.description,",
            "  icon = EXCLUDED.icon, icon_bg = EXCLUDED.icon_bg, icon_color = EXCLUDED.icon_color, level = EXCLUDED.level,",
            "  duration = EXCLUDED.duration, lessons = EXCLUDED.lessons, skills = EXCLUDED.skills,",
            "  is_active = EXCLUDED.is_active, sort_order = EXCLUDED.sort_order;", "",
            "COMMIT;", "",
            "-- ── OPTIONAL: hide the older catalogue so learners only see the 7 tracks ──",
            "-- Uncomment once you have decided. Enrolled students keep their progress.",
            "-- UPDATE domains SET is_active = false WHERE id NOT IN (",
            "--   " + ", ".join(q(uid(t["code"])) for t in tracks) + ");",
            "-- UPDATE lp_programs SET is_active = false WHERE id NOT IN (",
            "--   " + ", ".join(q(uid(t["code"], "program")) for t in tracks) + ");", ""]

    path = ROOT / "rotech-tracks-seed.sql"
    path.write_text("\n".join(out), encoding="utf-8")
    n_mod = sum(t["weeks"] for t in tracks)
    print(f"wrote {path.name}: {len(tracks)} domains, {n_mod} modules, {n_mod * 4} lessons, {len(tracks)} programmes")


if __name__ == "__main__":
    build()
